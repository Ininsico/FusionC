package io.fusionc.backend;

import io.fusionc.ir.DType;
import io.fusionc.ir.IrGraph;
import io.fusionc.ir.IrNode;
import io.fusionc.ir.OpKind;
import io.fusionc.pass.FusionGroup;
import io.fusionc.pass.GroupKind;

import java.util.ArrayList;
import java.util.List;

/**
 * Emits one self-contained CUDA translation unit for a lowered, fused IR graph:
 * kernel definitions, a static memory plan, and a host harness that loads inputs, runs a warm-up
 * pass, times every region with CUDA events, dumps the result and reports ptxas-visible kernel
 * attributes (registers, shared memory, spills) at run time.
 */
public final class CudaEmitter {

    private final IrGraph graph;
    private final List<FusionGroup> groups;
    private final boolean fused;
    private final EmitContext ctx;
    private final CudaWriter w = new CudaWriter();

    public CudaEmitter(IrGraph graph, List<FusionGroup> groups, boolean fused) {
        this.graph = graph;
        this.groups = groups;
        this.fused = fused;
        this.ctx = new EmitContext(graph, groups, fused);
    }

    public String emit(String sourceFile) {
        header(sourceFile);
        deviceHelpers();
        for (FusionGroup group : groups) {
            emitKernel(group);
        }
        memoryPlan();
        harness();
        return w.text();
    }

    // ------------------------------------------------------------------ header

    private void header(String sourceFile) {
        w.line("// ===========================================================================");
        w.line("//  GENERATED by FusionC -- do not edit.");
        w.line("//  source      : %s", sourceFile);
        w.line("//  mode        : %s", fused ? "--fuse" : "--no-fusion");
        w.line("//  target      : CUDA C for sm_61 (Pascal GP10x: GTX 1050 Ti / GTX 1070)");
        w.line("//  constraints : no Tensor Cores, no cp.async (cooperative smem loads guarded by");
        w.line("//                __syncthreads()), 48 KB shared/block, 255 regs/thread,");
        w.line("//                FP16 storage with FP32 accumulation (GP10x FP16 math = 1/64 rate)");
        w.line("// ===========================================================================");
        w.line("#include <cuda_runtime.h>");
        w.line("#include <cuda_fp16.h>");
        w.line("#include <stdio.h>");
        w.line("#include <stdlib.h>");
        w.line("#include <string.h>");
        w.line("#include <math.h>");
        w.blank();
        w.line("#define FX_WARP 32");
        w.line("#define FX_SMEM_CAP %d", io.fusionc.pass.PascalHeuristics.MAX_SMEM_BYTES_PER_BLOCK);
        w.blank();
        w.line("#define FX_CUDA_CHECK(call) do { cudaError_t fx_err = (call); if (fx_err != cudaSuccess) { \\");
        w.line("    fprintf(stderr, \"CUDA error %s (%d) at %s:%d in %s\\n\", cudaGetErrorString(fx_err), (int) fx_err, __FILE__, __LINE__, #call); \\");
        w.line("    exit(2); } } while (0)");
        w.blank();
    }

    private void deviceHelpers() {
        w.line("// ---- device helpers shared by the generated kernels ----");
        w.line("__device__ __forceinline__ float fx_gelu(float v) {");
        w.in();
        w.line("return 0.5f * v * (1.0f + tanhf(0.7978845608f * (v + 0.044715f * v * v * v)));");
        w.out();
        w.line("}");
        w.blank();
        w.line("__device__ __forceinline__ float fx_warp_max(float v) {");
        w.in();
        w.line("#pragma unroll");
        w.line("for (int o = %d; o > 0; o >>= 1) v = fmaxf(v, __shfl_down_sync(0xffffffffu, v, o));", 16);
        w.line("return v;");
        w.out();
        w.line("}");
        w.blank();
        w.line("__device__ __forceinline__ float fx_warp_sum(float v) {");
        w.in();
        w.line("#pragma unroll");
        w.line("for (int o = 16; o > 0; o >>= 1) v += __shfl_down_sync(0xffffffffu, v, o);");
        w.line("return v;");
        w.out();
        w.line("}");
        w.blank();
        w.line("__device__ __forceinline__ float fx_block_max(float v, float* scratch) {");
        w.in();
        w.line("const int lane = threadIdx.x & 31, warp = threadIdx.x >> 5;");
        w.line("const int warps = (blockDim.x + 31) >> 5;");
        w.line("v = fx_warp_max(v);");
        w.line("if (lane == 0) scratch[warp] = v;");
        w.line("__syncthreads();");
        w.line("if (warp == 0) {");
        w.in();
        w.line("float t = (lane < warps) ? scratch[lane] : -INFINITY;");
        w.line("t = fx_warp_max(t);");
        w.line("if (lane == 0) scratch[0] = t;");
        w.out();
        w.line("}");
        w.line("__syncthreads();");
        w.line("const float r = scratch[0];");
        w.line("__syncthreads();   // keep scratch reusable by the next block reduction");
        w.line("return r;");
        w.out();
        w.line("}");
        w.blank();
        w.line("__device__ __forceinline__ float fx_block_sum(float v, float* scratch) {");
        w.in();
        w.line("const int lane = threadIdx.x & 31, warp = threadIdx.x >> 5;");
        w.line("const int warps = (blockDim.x + 31) >> 5;");
        w.line("v = fx_warp_sum(v);");
        w.line("if (lane == 0) scratch[warp] = v;");
        w.line("__syncthreads();");
        w.line("if (warp == 0) {");
        w.in();
        w.line("float t = (lane < warps) ? scratch[lane] : 0.0f;");
        w.line("t = fx_warp_sum(t);");
        w.line("if (lane == 0) scratch[0] = t;");
        w.out();
        w.line("}");
        w.line("__syncthreads();");
        w.line("const float r = scratch[0];");
        w.line("__syncthreads();   // keep scratch reusable by the next block reduction");
        w.line("return r;");
        w.out();
        w.line("}");
        w.blank();
    }

    // ------------------------------------------------------------------ kernels

    private void emitKernel(FusionGroup group) {
        switch (group.kind) {
            case SINGLE:
                switch (group.members.get(0).op) {
                    case MATMUL:
                        GemmKernels.emit(w, group, ctx);
                        break;
                    case SOFTMAX:
                    case LAYERNORM:
                        ReduceKernels.emit(w, group, ctx);
                        break;
                    case BIAS_ADD:
                    case RELU:
                    case GELU:
                    case SCALE:
                    case ADD:
                        ElementwiseKernels.emit(w, group, ctx);
                        break;
                    default:
                        throw new IllegalStateException("no emitter for op " + group.members.get(0).op
                                + " in group " + group.id + " -- refusing to emit incomplete code");
                }
                break;
            case GEMM_EPILOGUE:
                GemmKernels.emit(w, group, ctx);
                break;
            case ELEMENTWISE_FUSED:
                ElementwiseKernels.emit(w, group, ctx);
                break;
            case ATTENTION_FUSED:
                AttentionKernel.emit(w, group, ctx);
                break;
            case GEMM_GEMM_FUSED:
                MlpKernel.emit(w, group, ctx);
                break;
            default:
                throw new IllegalStateException("no emitter for group kind " + group.kind);
        }
    }

    private LaunchConfig launchFor(FusionGroup group) {
        switch (group.kind) {
            case SINGLE:
                switch (group.members.get(0).op) {
                    case MATMUL:
                        return GemmKernels.launch(group, ctx);
                    case SOFTMAX:
                    case LAYERNORM:
                        return ReduceKernels.launch(group, ctx);
                    default:
                        return ElementwiseKernels.launch(group, ctx);
                }
            case GEMM_EPILOGUE:
                return GemmKernels.launch(group, ctx);
            case ELEMENTWISE_FUSED:
                return ElementwiseKernels.launch(group, ctx);
            case ATTENTION_FUSED:
                return AttentionKernel.launch(group, ctx);
            case GEMM_GEMM_FUSED:
                return MlpKernel.launch(group, ctx);
            default:
                throw new IllegalStateException("no launch config for " + group.kind);
        }
    }

    // --------------------------------------------------------------- memory plan

    private void memoryPlan() {
        List<IrNode> buffers = ctx.buffers();
        IrNode output = graph.outputs.get(graph.outputs.size() - 1);
        w.line("// ============================ static memory plan ============================");
        w.line("#define FX_TENSORS %d", buffers.size());
        w.line("static const char* const FX_TENSOR_NAME[FX_TENSORS] = {");
        w.in();
        for (int i = 0; i < buffers.size(); i++) {
            IrNode n = buffers.get(i);
            w.line("\"%s\"%s", n.name, i + 1 < buffers.size() ? "," : "");
        }
        w.out();
        w.line("};");
        w.line("static const long FX_TENSOR_ELEMS[FX_TENSORS] = {");
        w.in();
        for (int i = 0; i < buffers.size(); i++) {
            w.line("%dL%s", buffers.get(i).shape.elements(), i + 1 < buffers.size() ? "," : "");
        }
        w.out();
        w.line("};");
        w.line("static const int FX_TENSOR_ESIZE[FX_TENSORS] = {");
        w.in();
        for (int i = 0; i < buffers.size(); i++) {
            w.line("%d%s", buffers.get(i).store.sizeBytes, i + 1 < buffers.size() ? "," : "");
        }
        w.out();
        w.line("};");
        w.line("// -1 = produced on device, otherwise index of the host tensor to load from disk");
        w.line("static const int FX_TENSOR_HOST[FX_TENSORS] = {");
        w.in();
        int hostIndex = 0;
        List<Integer> hostIndexes = new ArrayList<>();
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < buffers.size(); i++) {
            int index = buffers.get(i).isLeaf() ? hostIndex++ : -1;
            hostIndexes.add(index);
            sb.append(index).append(i + 1 < buffers.size() ? ", " : "");
        }
        w.line(sb.toString());
        w.out();
        w.line("};");
        w.line("#define FX_OUTPUT %d", ctx.bufferOf(output));
        w.line("static void* g_tensor[FX_TENSORS];");
        w.blank();
        for (IrNode n : buffers) {
            w.line("#define %s ((%s*)g_tensor[%d])", ctx.ptr(n),
                    n.isLeaf() ? "const " + n.store.cType : n.store.cType, ctx.bufferOf(n));
        }
        w.blank();
    }

    // ------------------------------------------------------------------ harness

    private void harness() {
        List<FusionGroup> emitted = new ArrayList<>();
        for (FusionGroup group : groups) {
            if (group.members.get(0).isLeaf()) {
                continue;
            }
            emitted.add(group);
        }

        w.line("// ============================== regions ==============================");
        w.line("#define FX_REGIONS %d", emitted.size());
        w.line("static const char* const FX_REGION_NAME[FX_REGIONS] = {");
        w.in();
        for (int i = 0; i < emitted.size(); i++) {
            w.line("\"%s\"%s", emitted.get(i).regionName(), i + 1 < emitted.size() ? "," : "");
        }
        w.out();
        w.line("};");
        w.blank();
        w.line("// One entry per emitted kernel, for the ptxas-independent resource report.");
        w.line("#define FX_KERNELS %d", emitted.size());
        w.line("static const char* const FX_KERNEL_NAME[FX_KERNELS] = {");
        w.in();
        for (int i = 0; i < emitted.size(); i++) {
            w.line("\"%s\"%s", FusionGroup.kernelName(emitted.get(i).kind, emitted.get(i).id,
                    emitted.get(i).members), i + 1 < emitted.size() ? "," : "");
        }
        w.out();
        w.line("};");
        w.line("static const void* const FX_KERNEL_PTR[FX_KERNELS] = {");
        w.in();
        for (int i = 0; i < emitted.size(); i++) {
            FusionGroup g = emitted.get(i);
            w.line("(const void*)%s%s", FusionGroup.kernelName(g.kind, g.id, g.members),
                    i + 1 < emitted.size() ? "," : "");
        }
        w.out();
        w.line("};");
        w.blank();

        w.line("// ---- launch sequence: one region per fusion group, in dependency order ----");
        w.line("static void fx_launch_all(cudaEvent_t* evStart, cudaEvent_t* evStop, int measure) {");
        w.in();
        for (int i = 0; i < emitted.size(); i++) {
            FusionGroup g = emitted.get(i);
            LaunchConfig cfg = launchFor(g);
            w.line("// region %d: %s", i, g.regionName());
            w.line("if (measure) FX_CUDA_CHECK(cudaEventRecord(evStart[%d], 0));", i);
            w.line("%s<<<%s, %d>>> (%s);",
                    FusionGroup.kernelName(g.kind, g.id, g.members),
                    cfg.gridExpression().contains("dim3") ? cfg.gridExpression() : cfg.gridExpression(),
                    cfg.block, ctx.launchArgs(g));
            w.line("if (measure) FX_CUDA_CHECK(cudaEventRecord(evStop[%d], 0));", i);
        }
        w.line("FX_CUDA_CHECK(cudaGetLastError());");
        w.out();
        w.line("}");
        w.blank();

        w.line(harnessMain());
    }

    private String harnessMain() {
        return String.join("\n",
"static double fx_now_ms(cudaEvent_t a, cudaEvent_t b) {",
"    float ms = 0.0f;",
"    FX_CUDA_CHECK(cudaEventElapsedTime(&ms, a, b));",
"    return (double) ms;",
"}",
"",
"static void fx_load_tensor(int index, const char* dir) {",
"    char path[1024];",
"    snprintf(path, sizeof(path), \"%s/%s.bin\", dir, FX_TENSOR_NAME[index]);",
"    FILE* f = fopen(path, \"rb\");",
"    if (!f) { fprintf(stderr, \"cannot open input tensor '%s'\\n\", path); exit(3); }",
"    const long bytes = FX_TENSOR_ELEMS[index] * FX_TENSOR_ESIZE[index];",
"    void* host = malloc((size_t) bytes);",
"    if (!host) { fprintf(stderr, \"out of host memory\\n\"); exit(3); }",
"    const size_t got = fread(host, 1, (size_t) bytes, f);",
"    fclose(f);",
"    if (got != (size_t) bytes) {",
"        fprintf(stderr, \"input '%s' has %zu bytes, expected %ld\\n\", path, got, bytes);",
"        exit(3);",
"    }",
"    FX_CUDA_CHECK(cudaMemcpy(g_tensor[index], host, (size_t) bytes, cudaMemcpyHostToDevice));",
"    free(host);",
"}",
"",
"int main(int argc, char** argv) {",
"    const char* inputDir = NULL;",
"    const char* outFile = NULL;",
"    const char* timingFile = NULL;",
"    const char* dumpDir = NULL;",
"    int iters = 100, warmup = 20, device = 0;",
"    for (int i = 1; i < argc; ++i) {",
"        if (!strcmp(argv[i], \"--inputs\") && i + 1 < argc) inputDir = argv[++i];",
"        else if (!strcmp(argv[i], \"--out\") && i + 1 < argc) outFile = argv[++i];",
"        else if (!strcmp(argv[i], \"--timings\") && i + 1 < argc) timingFile = argv[++i];",
"        else if (!strcmp(argv[i], \"--dump-all\") && i + 1 < argc) dumpDir = argv[++i];",
"        else if (!strcmp(argv[i], \"--iters\") && i + 1 < argc) iters = atoi(argv[++i]);",
"        else if (!strcmp(argv[i], \"--warmup\") && i + 1 < argc) warmup = atoi(argv[++i]);",
"        else if (!strcmp(argv[i], \"--device\") && i + 1 < argc) device = atoi(argv[++i]);",
"        else { fprintf(stderr, \"unknown argument '%s'\\n\", argv[i]); return 1; }",
"    }",
"    FX_CUDA_CHECK(cudaSetDevice(device));",
"    cudaDeviceProp prop;",
"    FX_CUDA_CHECK(cudaGetDeviceProperties(&prop, device));",
"    printf(\"DEVICE,%s,%d.%d,%d,%d,%d,%d,%d,%d\\n\", prop.name, prop.major, prop.minor,",
"           prop.multiProcessorCount, prop.regsPerMultiprocessor, (int) prop.sharedMemPerBlock,",
"           (int) prop.sharedMemPerMultiprocessor, prop.maxThreadsPerMultiProcessor,",
"           prop.clockRate);",
"",
"    for (int i = 0; i < FX_TENSORS; ++i) {",
"        FX_CUDA_CHECK(cudaMalloc(&g_tensor[i], FX_TENSOR_ELEMS[i] * FX_TENSOR_ESIZE[i]));",
"    }",
"    if (inputDir) {",
"        for (int i = 0; i < FX_TENSORS; ++i) {",
"            if (FX_TENSOR_HOST[i] >= 0) fx_load_tensor(i, inputDir);",
"        }",
"    }",
"",
"    // report the register / shared-memory / spill footprint of every emitted kernel",
"    for (int k = 0; k < FX_KERNELS; ++k) {",
"        cudaFuncAttributes attr;",
"        if (cudaFuncGetAttributes(&attr, FX_KERNEL_PTR[k]) == cudaSuccess) {",
"            printf(\"KERNELATTR,%s,%d,%d,%d,%d\\n\", FX_KERNEL_NAME[k], attr.numRegs,",
"                   (int) attr.sharedSizeBytes, (int) attr.localSizeBytes, attr.maxThreadsPerBlock);",
"        }",
"    }",
"",
"    for (int i = 0; i < warmup; ++i) fx_launch_all(NULL, NULL, 0);",
"    FX_CUDA_CHECK(cudaDeviceSynchronize());",
"",
"    cudaEvent_t regStart[FX_REGIONS], regStop[FX_REGIONS];",
"    double regionMs[FX_REGIONS];",
"    for (int r = 0; r < FX_REGIONS; ++r) {",
"        FX_CUDA_CHECK(cudaEventCreate(&regStart[r]));",
"        FX_CUDA_CHECK(cudaEventCreate(&regStop[r]));",
"        regionMs[r] = 0.0;",
"    }",
"    for (int it = 0; it < iters; ++it) {",
"        fx_launch_all(regStart, regStop, 1);",
"        FX_CUDA_CHECK(cudaDeviceSynchronize());",
"        for (int r = 0; r < FX_REGIONS; ++r) regionMs[r] += fx_now_ms(regStart[r], regStop[r]);",
"    }",
"",
"    cudaEvent_t t0, t1;",
"    FX_CUDA_CHECK(cudaEventCreate(&t0));",
"    FX_CUDA_CHECK(cudaEventCreate(&t1));",
"    for (int i = 0; i < warmup; ++i) fx_launch_all(NULL, NULL, 0);",
"    FX_CUDA_CHECK(cudaDeviceSynchronize());",
"    FX_CUDA_CHECK(cudaEventRecord(t0, 0));",
"    for (int it = 0; it < iters; ++it) fx_launch_all(NULL, NULL, 0);",
"    FX_CUDA_CHECK(cudaEventRecord(t1, 0));",
"    FX_CUDA_CHECK(cudaEventSynchronize(t1));",
"    const double totalMs = fx_now_ms(t0, t1) / iters;",
"",
"    for (int r = 0; r < FX_REGIONS; ++r) {",
"        printf(\"REGION,%s,%.6f\\n\", FX_REGION_NAME[r], regionMs[r] / iters);",
"    }",
"    printf(\"TOTAL,%.6f\\n\", totalMs);",
"",
"    // result: checksum in float64 and raw dump for the reference comparison",
"    const long outElems = FX_TENSOR_ELEMS[FX_OUTPUT];",
"    const int outEsize = FX_TENSOR_ESIZE[FX_OUTPUT];",
"    void* hostOut = malloc((size_t) outElems * outEsize);",
"    FX_CUDA_CHECK(cudaMemcpy(hostOut, g_tensor[FX_OUTPUT], (size_t) outElems * outEsize,",
"                             cudaMemcpyDeviceToHost));",
"    double checksum = 0.0;",
"    for (long i = 0; i < outElems; ++i) {",
"        checksum += (outEsize == 2) ? (double) __half2float(((const __half*) hostOut)[i])",
"                                    : (double) ((const float*) hostOut)[i];",
"    }",
"    printf(\"CHECKSUM,%.9f\\n\", checksum);",
"    printf(\"OUTPUT,%s,%ld,%d\\n\", FX_TENSOR_NAME[FX_OUTPUT], outElems, outEsize);",
"    if (outFile) {",
"        FILE* f = fopen(outFile, \"wb\");",
"        if (!f) { fprintf(stderr, \"cannot write '%s'\\n\", outFile); return 3; }",
"        fwrite(hostOut, 1, (size_t) outElems * outEsize, f);",
"        fclose(f);",
"    }",
"    if (timingFile) {",
"        FILE* f = fopen(timingFile, \"w\");",
"        if (f) {",
"            fprintf(f, \"region,ms_per_iter\\n\");",
"            for (int r = 0; r < FX_REGIONS; ++r) {",
"                fprintf(f, \"\\\"%s\\\",%.6f\\n\", FX_REGION_NAME[r], regionMs[r] / iters);",
"            }",
"            fprintf(f, \"\\\"TOTAL\\\",%.6f\\n\", totalMs);",
"            fclose(f);",
"        }",
"    }",
"    if (dumpDir) {   // every materialised tensor, so intermediate results can be verified",
"        for (int i = 0; i < FX_TENSORS; ++i) {",
"            char path[1200];",
"            snprintf(path, sizeof(path), \"%s/%s.bin\", dumpDir, FX_TENSOR_NAME[i]);",
"            FILE* f = fopen(path, \"wb\");",
"            if (!f) continue;",
"            const size_t bytes = (size_t) FX_TENSOR_ELEMS[i] * FX_TENSOR_ESIZE[i];",
"            void* host = malloc(bytes);",
"            if (host) {",
"                if (cudaMemcpy(host, g_tensor[i], bytes, cudaMemcpyDeviceToHost) == cudaSuccess) {",
"                    fwrite(host, 1, bytes, f);",
"                }",
"                free(host);",
"            }",
"            fclose(f);",
"        }",
"    }",
"    free(hostOut);",
"    for (int i = 0; i < FX_TENSORS; ++i) cudaFree(g_tensor[i]);",
"    return 0;",
"}",
"");
    }
}
